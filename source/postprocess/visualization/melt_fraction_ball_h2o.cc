      template <int dim>
      double
      MeltFractionBallH2O<dim>::
      melt_fraction (const double temperature,
                     const double pressure,
                     const std::string &melting_model) const
      {
        if (melting_model == "peridotite")
          {
            //Hydrous melting of peridotite after Katz, 2003.
            const double T_solidus  = A1 + 273.15
                                      + A2 * pressure
                                      + A3 * pressure * pressure;
            const double T_lherz_liquidus = B1 + 273.15
                                            + B2 * pressure
                                            + B3 * pressure * pressure;
            const double T_liquidus = C1 + 273.15
                                      + C2 * pressure
                                      + C3 * pressure * pressure;

            //Melt fraction after melting of all clinopyroxene.
            //Eqn. 7 Katz et al 2003.
            const double R_cpx = r1 + r2 * std::max(0.0, pressure);

            //When R_cpx gets to 0 ald lower, F_cpx_out = 1. This extension solves the problem generated by r2<0 in Ball et al (2022).
            //Eqn. 6 Katz et al 2003.
            const double F_cpx_out = (R_cpx <= 0.0 ? 1.0 : std::min(1.0, M_cpx / R_cpx));

            //Eqn. 9 Katz et al 2003.
            const double T_cpx_out = std::pow(F_cpx_out, 1.0 / beta1) * (T_lherz_liquidus - T_solidus) + T_solidus;

            //Hydrous version of eqn. 3 Katz et al 2003 (before cpx is out).
            const auto check_cpx = [&](const double F)
            {
              return (temperature - T_solidus + calc_delta_T_H2O(F))
                     / (T_lherz_liquidus - T_solidus);
            };

            //Root chasing. Eqn. 2 Katz et al 2003.
            const auto func_cpx = [&](const double F)
            {
              const double T_prime = check_cpx(F);
              return F - std::pow(T_prime, beta1);
            };

            //Hydrous version of eqn. 3 Katz et al 2003 (after cpx is out).
            const auto check_opx = [&](const double F)
            {
              return (temperature - T_cpx_out + calc_delta_T_H2O(F))
                     / (T_liquidus - T_cpx_out);
            };

            //Root chasing. Eqn. 8 Katz et al 2003.
            const auto func_opx = [&](const double F)
            {
              const double T_prime = check_opx(F);

              return F - F_cpx_out
                     - (1.0 - F_cpx_out) * std::pow(T_prime, beta2);
            };

            //Iterative algorithm to chase a root-finding bracket.
            const auto det_bracket =
              [&](const double start,
                  const double stop,
                  const unsigned int nb_incrmt,
                  const auto &func_check,
                  const auto &func,
                  double &bracket_low,
                  double &bracket_high) -> bool
            {
              double F = start;
              double incrmt = 0.0;

              for (unsigned int i = 0; i < nb_incrmt; ++i)
                {
                  incrmt = std::pow(10.0, -static_cast<double>(i + 1));

                  const double func_check_start = func_check(start);

                  if (func_check_start <= 0.0)
                    return false;

                  const double func_start = func(start);

                  while (F < stop)
                    {
                      const double func_check_F = func_check(F);

                      if (func_check_F >= 0.0)
                        {
                          const double func_F = func(F);

                          if (std::isfinite(func_F))
                            {
                              if (func_F * func_start < 0.0)
                                {
                                  bracket_low  = F - incrmt;
                                  bracket_high = F;
                                  return true;
                                }
                              else
                                F += incrmt;
                            }
                          else
                            break;
                        }
                      else
                        break;
                    }

                  F -= incrmt;
                }

              bracket_low  = F;
              bracket_high = F + incrmt;

              return true;
            };

            //Boost TOMS748 root finder within the bracket:
            const auto solve_root =
              [&](const auto &func,
                  const double a,
                  const double b) -> double
            {
              const double fa = func(a);
              const double fb = func(b);

              if (fa == 0.0)
                return a;

              if (fb == 0.0)
                return b;

              AssertThrow(fa * fb < 0.0,
              ExcMessage("Root is not bracketed."));

              boost::uintmax_t max_iter = 100;

              const auto tolerance =
              [](const double left, const double right)
              {
                return std::abs(right - left) < 1e-12;
              };

              const auto result =
                boost::math::tools::toms748_solve(func, a, b, fa, fb, tolerance, max_iter);

              return 0.5 * (result.first + result.second);
            };

            double bracket_low;
            double bracket_high;

            const bool valid_cpx = det_bracket(0.0, F_cpx_out, 9, check_cpx, func_cpx, bracket_low, bracket_high);

            double peridotite_melt_fraction;
            //Cutout effect test:
            //if (pressure > 7.99e9)
            //  std::cout << std::setprecision(17)
            //            << "pressure = " << pressure
            //            << std::endl;
            //

            if (pressure > 8.0e9)
              {
                peridotite_melt_fraction = 0.0;
              }
            else if (!valid_cpx)
              {
                peridotite_melt_fraction = 0.0;
              }
            else if (bracket_high < F_cpx_out)
              {
                peridotite_melt_fraction = solve_root(func_cpx, bracket_low, bracket_high);

                if (peridotite_melt_fraction > 0.0)
                  peridotite_melt_fraction = check_water_saturation(pressure, temperature, peridotite_melt_fraction, T_solidus, T_lherz_liquidus);
              }
            else
              {
                //cpx exhausted.
                double bracket_low_opx;
                double bracket_high_opx;

                const bool valid_opx = det_bracket(F_cpx_out, 1.0, 9, check_opx, func_opx, bracket_low_opx, bracket_high_opx);

                Assert(valid_opx, ExcInternalError());

                if (bracket_high_opx >= 1.0)
                  peridotite_melt_fraction = 1.0;
                else
                  peridotite_melt_fraction = solve_root(func_opx, bracket_low_opx, bracket_high_opx);
              }

            return peridotite_melt_fraction;
          }
        else if (melting_model == "pyroxenite")
          {
            // melting of pyroxenite after Sobolev et al., 2011
            const double T_melting = D1 + 273.15
                                     + D2 * pressure
                                     + D3 * pressure * pressure;

            const double discriminant = E1*E1/(E2*E2*4) + (temperature-T_melting)/E2;

            double pyroxenite_melt_fraction;

            if (temperature < T_melting || pressure > 1.3e10)
              pyroxenite_melt_fraction = 0.0;
            else if (discriminant < 0)
              pyroxenite_melt_fraction = 0.5429;
            else
              pyroxenite_melt_fraction = -E1/(2*E2) - std::sqrt(discriminant);

            return pyroxenite_melt_fraction;
          }
        else
          {
            // throw an error if the melting model is not implemented
            AssertThrow(false, ExcMessage("The selected melting model is not implemented."));
          }
      }

      template <int dim>
      void
      MeltFractionBallH2O<dim>::
      evaluate_vector_field(const DataPostprocessorInputs::Vector<dim> &input_data,
                            std::vector<Vector<double>> &computed_quantities) const
      {
        const unsigned int n_quadrature_points = input_data.solution_values.size();
        Assert (computed_quantities.size() == n_quadrature_points,    ExcInternalError());
        Assert (computed_quantities[0].size() == 1,                   ExcInternalError());
        Assert (input_data.solution_values[0].size() == this->introspection().n_components,           ExcInternalError());

        // in case the material model computes the melt fraction itself, we use that output
        if (MaterialModel::MeltFractionModel<dim>::is_melt_fraction_model(this->get_material_model()))
          {
            MaterialModel::MaterialModelInputs<dim> in(input_data,
                                                       this->introspection());
            MaterialModel::MaterialModelOutputs<dim> out(n_quadrature_points,
                                                         this->n_compositional_fields());
            MeltHandler<dim>::create_material_model_outputs(out);

            // Compute the melt fraction...
            this->get_material_model().evaluate(in, out);

            std::vector<double> melt_fractions(n_quadrature_points);
            MaterialModel::MeltFractionModel<dim>::as_melt_fraction_model(this->get_material_model())
            .melt_fractions(in, melt_fractions, &out);

            for (unsigned int q=0; q<n_quadrature_points; ++q)
              computed_quantities[q](0) = melt_fractions[q];
          }
        else
          for (unsigned int q=0; q<n_quadrature_points; ++q)
            {
              const double pressure    = input_data.solution_values[q][this->introspection().component_indices.pressure];
              const double temperature = input_data.solution_values[q][this->introspection().component_indices.temperature];
              std::vector<double> composition(this->n_compositional_fields());

              for (unsigned int c=0; c<this->n_compositional_fields(); ++c)
                composition[c] = input_data.solution_values[q][this->introspection().component_indices.compositional_fields[c]];

              // Calculate the melt fraction for the background material (peridotite)
              const double peridotite_melt_fraction = melt_fraction(temperature, pressure, "peridotite");
              // Calculate the melt fraction for the non peridotite compositional field
              double total_melt_fraction = 0.0;
              double total_comp_fraction = 0.0;

              for (const auto &model : melting_model)
                {
                  const unsigned int comp_index = this->introspection().compositional_index_for_name(model);
                  const double comp_melt_fraction = melt_fraction(temperature, pressure, model);
                  total_melt_fraction += composition[comp_index] * comp_melt_fraction;
                  total_comp_fraction += composition[comp_index];
                }
              if (total_comp_fraction > 1.0)
                AssertThrow(false, ExcMessage("The total fraction of non-peridotite compositional fields exceeds 1.0. "
                                              "Please check the input file and ensure that the sum of all compositional fields is less than or equal to 1.0."));
              total_melt_fraction += (1.0 - total_comp_fraction) * peridotite_melt_fraction;

              computed_quantities[q](0) = total_melt_fraction;
            }
      }



