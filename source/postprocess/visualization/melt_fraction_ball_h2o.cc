      //Eqn. 18 Katz et al (2003): melt water concentration.
      template <int dim>
      double
      MeltFractionBallH2O<dim>::calc_X_H2O(const double F) const
      {
        //The unit Katz et al (2003) works with is %wt, so ppms are converted to it.
        const double X_H2O_bulk = bulk_h2o_ppm / 10000.0;

        return X_H2O_bulk /
               (D_H2O + F * (1.0 - D_H2O));
      }
      //Eqn. 16 Katz et al (2003): deltaT.
      template <int dim>
      double
      MeltFractionBallH2O<dim>::calc_delta_T_H2O(const double F) const
      {
        return K_H2O * std::pow(calc_X_H2O(F), gamma_H2O);
      }

      //The water concentration of melt is bounded to the water saturation.
      template <int dim>
      double
      MeltFractionBallH2O<dim>::check_water_saturation(
        const double pressure,
        const double temperature,
        const double F,
        const double T_solidus,
        const double T_lherz_liquidus) const
      {
        const double pressure_GPa = pressure / 1.0e9;

        //Eqn. 17 Katz et al (2003): water saturation.
        const double X_H2O_sat = k1_H2O * std::pow(pressure_GPa, lambda_H2O) + k2_H2O * pressure_GPa;

        double F_corrected = F;

        //Eqn. 2 and eqn. 19 Katz et al (2003) are the anhydrous and hydrous version of the same eqn.
        //Eqn. 19 Katz et al (2003): with usage of water saturation instead of melt water concentration:
        if (calc_X_H2O(F) > X_H2O_sat)
          {
            const double T_prime =
              (temperature - T_solidus + K_H2O * std::pow(X_H2O_sat, gamma_H2O))
              / (T_lherz_liquidus - T_solidus);

            F_corrected = (T_prime > 0.0) ? std::pow(T_prime, beta1) : 0.0;
          }

        return F_corrected;
      }

